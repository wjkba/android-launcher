#!/usr/bin/env python3
"""Imports Material Symbols (Rounded, weight 300, outlined) as Android vector drawables.

Usage: python3 scripts/import_icons.py

Writes app/src/main/res/drawable/{folder_icon,ui_icon}_<name>.xml and the Kotlin registry
FolderIconSet.kt. Edit FOLDER_ICONS / UI_ICONS below and re-run to change the set.
Source: https://github.com/google/material-design-icons (Apache 2.0, see third_party/material-symbols).
"""

import pathlib
import re
import sys
import urllib.request

# Pinned so a re-run produces the same files.
COMMIT = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
URL = (
    "https://raw.githubusercontent.com/google/material-design-icons/{commit}/symbols/web/"
    "{name}/materialsymbolsrounded/{name}_wght300_24px.svg"
)

# Icons a folder can use, in picker order. The first one is the default.
FOLDER_ICONS = [
    "folder", "star", "favorite", "bolt", "home", "work", "school", "chat",
    "call", "mail", "forum", "group", "person", "public", "photo_camera", "image",
    "movie", "music_note", "headphones", "podcasts", "sports_esports", "menu_book", "edit_note", "calendar_month",
    "schedule", "checklist", "payments", "account_balance", "shopping_bag", "shopping_cart", "restaurant", "local_cafe",
    "directions_car", "directions_bus", "flight", "map", "fitness_center", "directions_run", "spa", "pets",
    "eco", "wb_sunny", "build", "settings", "terminal", "lock", "lightbulb", "newspaper",
]

# Icons used by the launcher's own UI.
UI_ICONS = ["arrow_back", "edit", "check"]

ROOT = pathlib.Path(__file__).resolve().parent.parent
DRAWABLES = ROOT / "app/src/main/res/drawable"
REGISTRY = ROOT / "app/src/main/java/dev/minimal/launcher/core/designsystem/FolderIconSet.kt"

VECTOR = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols "{name}" (Rounded, weight 300), Apache 2.0. Generated by scripts/import_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <!-- The SVG viewBox is "0 -960 960 960"; shift it into the drawable's 0..960 viewport. -->
    <group android:translateY="960">
        <path
            android:fillColor="#FFFFFFFF"
            android:pathData="{path}" />
    </group>
</vector>
"""

REGISTRY_TEMPLATE = """package dev.minimal.launcher.core.designsystem

import dev.minimal.launcher.R

// Generated by scripts/import_icons.py; edit the list there and re-run instead of changing this file.

/** Icons a folder can use, as (stable key, drawable). The key is what gets stored; drawable ids change per build. */
internal val folderIconSet: List<Pair<String, Int>> = listOf(
{entries}
)
"""


def fetch_path(name: str) -> str:
    url = URL.format(commit=COMMIT, name=name)
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            svg = response.read().decode()
    except Exception as error:  # noqa: BLE001 - report which icon failed and stop
        sys.exit(f"{name}: cannot download {url}: {error}")
    if 'viewBox="0 -960 960 960"' not in svg:
        sys.exit(f"{name}: unexpected viewBox")
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if len(paths) != 1:
        sys.exit(f"{name}: expected exactly one <path>, found {len(paths)}")
    return paths[0]


def main() -> None:
    for prefix, names in (("folder_icon", FOLDER_ICONS), ("ui_icon", UI_ICONS)):
        for name in names:
            xml = VECTOR.format(name=name, path=fetch_path(name))
            (DRAWABLES / f"{prefix}_{name}.xml").write_text(xml)
            print(f"{prefix}_{name}")
    entries = "\n".join(f'    "{name}" to R.drawable.folder_icon_{name},' for name in FOLDER_ICONS)
    REGISTRY.write_text(REGISTRY_TEMPLATE.format(entries=entries))


if __name__ == "__main__":
    main()
